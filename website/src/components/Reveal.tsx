"use client";

import { useEffect, useRef, useState, type ReactNode } from "react";

/**
 * Fades/slides children in once they scroll into view. Degrades safely: content
 * is only ever hidden via a CSS class this component controls (see the
 * <noscript> override in layout.tsx for the no-JS case), and reduced-motion users
 * get the global near-instant transition instead of no reveal at all — see
 * globals.css's prefers-reduced-motion block.
 */
export default function Reveal({
  children,
  className = "",
  delay = 0,
}: {
  children: ReactNode;
  className?: string;
  delay?: number;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setVisible(true);
          observer.disconnect();
        }
      },
      { threshold: 0.15, rootMargin: "0px 0px -60px 0px" }
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={`reveal ${visible ? "reveal-visible" : ""} ${className}`}
      style={{ transitionDelay: visible ? `${delay}ms` : "0ms" }}
    >
      {children}
    </div>
  );
}
